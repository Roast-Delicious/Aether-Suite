import hub_layout as L

def page(p):
    p.title('Action Bar Area', 'Your bars, chat, meter and XP bar')
    p.band('Panels', 'Bars, Chat, Meter')
    p.check('Aether panel behind your action bars')
    p.check('Aether panel behind your chat')
    p.slider('Panels in combat', 0.8, '80%')
    p.slider('Panels out of combat', 0.3, '30%')
    p.band('Action bars', 'AetherBars')
    p.slider('Bars when idle', 0.6, '60%')
    p.check('Solid in combat', ux=0, row_end=False); p.check('Solid under your mouse', ux=210)
    p.slider('Icon edge darkness', 0.85, '85%')
    p.check('Cooldown glow (orange after use, green when ready)')
    p.check('Macro names on buttons', ux=0, row_end=False); p.check('Hide Blizzard\'s bar art', ux=210)
    p.choice('Match button size to Action Bar 1', ['Bar 2', 'All Bars', 'Off'], 'Bar 2')
    p.check('Center the bars when aligning')
    p.buttons(['Align Bars...', 'Undo Last Align', 'Open Edit Mode'])
    p.band('XP bar', 'AetherBars')
    p.slider('Width', 0.55, '800', new=True)
    p.slider('Height', 0.3, '8', new=True)
    p.band('Chat', 'AetherChat')
    p.check('Chat fits left of your bars')
    p.check('Hide the voice, channel and emote buttons')
    p.check('Slim typing line, only while you type')
    p.slider('Chat text size', 0.42, '13')
    p.buttons(['Fit Chat Now'])
    p.band('Meter', 'AetherMeter')
    p.check('Show the meter', ux=0, row_end=False); p.check('Lock the meter', ux=210)
    p.choice('Show', ['DPS and HPS', 'DPS only', 'HPS only'], 'DPS and HPS')
    p.check('Split DPS and HPS into two windows', on=False)
    p.check('Meter docks right of your bars')
    p.buttons(['Preview Meter'])
    p.gap(4)
    p.buttons(['!Restore Defaults...'])

L.render_b('Action Bar Area', page, 'out_hub_bars')
